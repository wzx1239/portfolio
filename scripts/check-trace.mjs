import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import { stripTypeScriptTypes } from 'node:module';

const uri=source=>'data:text/javascript;base64,'+Buffer.from(source).toString('base64');
const compile=async file=>stripTypeScriptTypes(await readFile(new URL('../'+file,import.meta.url),'utf8'));
const settingsURI=uri(await compile('components/trace/trace-settings.ts'));
const {traceSettings:settings}=await import(settingsURI);
const bindSettings=source=>source.replace(/from ['"]\.\/trace-settings['"]/g,`from '${settingsURI}'`);
const {TraceMemory}=await import(uri(bindSettings(await compile('components/trace/trace-memory.ts'))));
const {traceMask}=await import(uri(bindSettings(await compile('components/trace/trace-mask.ts'))));
const draw=(speed)=>{const m=new TraceMemory();for(let i=0;i<=20;i++)m.add({x:100+i*20,y:100+Math.sin(i/3)*40,time:i*16,speed});return m;};
const slow=draw(.03),fast=draw(1),now=320;
assert(fast.read(now)[0].strength>slow.read(now)[0].strength*30,'Velocity must change energy substantially');
const fields=fast.read(now+350);
assert(fields.length>1,'The stopped pointer must leave multiple previous path portions');
assert(fields.some(f=>f.ax<200),'Earlier positions must survive after passage');
assert(fields[0].radius>fields[0].width,'Residual area must diffuse');
assert(Math.hypot(fields[0].driftX,fields[0].driftY)>0,'Residual needs bounded inertia');
assert(fields.every(f=>f.strength< f.energy),'Energy must fade after stopping');
assert.equal(fast.read(now+settings.fastDecay+1).length,0,'Field must recover completely');
const stationary=new TraceMemory();for(let i=0;i<100;i++)stationary.add({x:100,y:100,time:i*16,speed:1});
assert.equal(stationary.segments.length,0,'Still pointer must not paint a permanent blob');
const bounded=new TraceMemory();for(let i=0;i<2000;i++)bounded.add({x:i*5,y:50,time:i*16,speed:.6});
assert(bounded.segments.length<=settings.maxTraces,'History must have a fixed upper bound');
for(let i=1;i<bounded.segments.length;i++)assert.equal(bounded.segments[i].ax,bounded.segments[i-1].bx,'Segments must join without spatial gaps');
const before=bounded.segments[0].ay;bounded.translate(0,-100);assert.equal(bounded.segments[0].ay,before-100);
const count=bounded.segments.length;bounded.add({x:999,y:999,time:50000,speed:1});assert.equal(bounded.segments.length,count,'Re-entry must not connect across an idle teleport');
const mask=traceMask(fields,{left:0,top:0,width:400,height:300},1.5,0);
assert(mask.includes('data:image/svg+xml'),'Reveal must use the same residual geometry');
assert(!decodeURIComponent(mask).includes('<circle'),'No stamped circles');
const empty=decodeURIComponent(traceMask([],{left:0,top:0,width:400,height:300},1,0));
assert(!empty.includes('<path'),'Recovered mask must contain no stationary pointer shape');
console.log('Trace verified: connected bounded history, velocity, residual memory, diffusion, inertia, complete recovery, idle/re-entry, scroll anchoring and organic Reveal mask.');
